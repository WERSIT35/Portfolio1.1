// Writes src/app/utils/shot-sizes.ts: the real pixel size of every project screenshot, so
// <img width/height> match each file exactly (no aspect-ratio mismatch, no layout shift).
// Run after adding or replacing screenshots:  node scripts/shot-sizes.mjs
import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import sharp from 'sharp';

const root = 'public/assets/projects';
const sizes = {};
for (const dir of readdirSync(root, { withFileTypes: true })) {
  if (!dir.isDirectory()) continue;
  for (const file of readdirSync(join(root, dir.name))) {
    if (!file.endsWith('.webp') || file.includes('-800w')) continue;
    const { width, height } = await sharp(join(root, dir.name, file)).metadata();
    sizes[`/assets/projects/${dir.name}/${file}`] = { width, height };
  }
}
const body = Object.entries(sizes)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([src, s]) => `  '${src}': { width: ${s.width}, height: ${s.height} },`)
  .join('\n');
writeFileSync(
  'src/app/utils/shot-sizes.ts',
  `// Generated by scripts/shot-sizes.mjs — do not edit by hand.\nexport const SHOT_SIZES: Record<string, { width: number; height: number }> = {\n${body}\n};\n`,
);
console.log(Object.keys(sizes).length, 'screenshots measured');
